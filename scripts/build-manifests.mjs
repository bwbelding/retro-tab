// Generates one add-in-only XML manifest per ribbon tab from manifests/ribbon.mjs.
// Usage: node scripts/build-manifests.mjs  (writes dist/manifest-<key>.xml)
// RETRO_BASE_URL overrides where the add-in is hosted (default: GitHub Pages).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ADDINS } from "../manifests/ribbon.mjs";

export const DEFAULT_BASE_URL = "https://bwbelding.github.io/retro-tab";
export const ICON_SIZES = [16, 32, 80];
const TASKPANE_ID = "RetroPane";

const esc = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** Every icon name a tab's manifest refers to (group icons, controls and menu items). */
export function iconsUsed(addin) {
  const names = new Set();
  for (const g of addin.groups) {
    names.add(g.icon);
    for (const c of g.controls) {
      if (c.office) continue;
      names.add(c.icon);
      for (const item of c.menu ?? []) names.add(item.icon);
    }
  }
  return [...names];
}

export function buildManifest(addin, { baseUrl = DEFAULT_BASE_URL, version = "0.0.0" } = {}) {
  const base = baseUrl.replace(/\/$/, "");
  const origin = new URL(base).origin;
  const viewUrl = (view) => `${base}/taskpane.html?tab=${addin.key}&view=${view}`;

  // Resource ids are limited to 32 characters, so they're short and sequential.
  const shortStrings = [];
  const longStrings = [];
  const urls = new Map();
  const short = (text) => (shortStrings.push(text), `S${shortStrings.length}`);
  const long = (text) => (longStrings.push(text), `L${longStrings.length}`);
  const url = (href) => {
    if (!urls.has(href)) urls.set(href, `U${urls.size + 1}`);
    return urls.get(href);
  };
  const icon = (name) =>
    `<Icon>${ICON_SIZES.map((s) => `<bt:Image size="${s}" resid="I.${name}.${s}"/>`).join("")}</Icon>`;
  const action = (view) =>
    `<Action xsi:type="ShowTaskpane"><TaskpaneId>${TASKPANE_ID}</TaskpaneId><SourceLocation resid="${url(viewUrl(view))}"/></Action>`;
  const tip = (c) => `<Supertip><Title resid="${short(c.label)}"/><Description resid="${long(c.tip)}"/></Supertip>`;
  const id = (local) => `${addin.key}.${local}`;

  const control = (c) => {
    if (c.office) return `<OfficeControl id="${esc(c.office)}"/>`;
    if (c.menu) {
      const items = c.menu
        .map((it) => `<Item id="${id(it.id)}"><Label resid="${short(it.label)}"/>${tip(it)}${icon(it.icon)}${action(it.view)}</Item>`)
        .join("");
      return `<Control xsi:type="Menu" id="${id(c.id)}"><Label resid="${short(c.label)}"/>${tip(c)}${icon(c.icon)}<Items>${items}</Items></Control>`;
    }
    return `<Control xsi:type="Button" id="${id(c.id)}"><Label resid="${short(c.label)}"/>${tip(c)}${icon(c.icon)}${action(c.view)}</Control>`;
  };

  const groups = addin.groups
    .map((g) => `<Group id="${id(g.id)}"><Label resid="${short(g.label)}"/>${icon(g.icon)}${g.controls.map(control).join("")}</Group>`)
    .join("\n");
  const tabLabel = short(addin.name);
  const commandsUrl = url(`${base}/commands.html`);

  const images = iconsUsed(addin)
    .flatMap((name) => ICON_SIZES.map((s) => `<bt:Image id="I.${name}.${s}" DefaultValue="${esc(`${base}/assets/icons/${name}-${s}.png`)}"/>`))
    .join("\n");
  const appIcon = (s) => esc(`${base}/assets/icons/retro-${s}.png`);
  const [major = 0, minor = 0, patch = 0] = version.split(".").map(Number);

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-manifests.mjs from manifests/ribbon.mjs. Do not edit by hand. -->
<OfficeApp xmlns="http://schemas.microsoft.com/office/appforoffice/1.1" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:bt="http://schemas.microsoft.com/office/officeappbasictypes/1.0" xmlns:ov="http://schemas.microsoft.com/office/taskpaneappversionoverrides" xsi:type="TaskPaneApp">
  <Id>${addin.id}</Id>
  <Version>${major}.${minor}.${patch}.0</Version>
  <ProviderName>bwbelding</ProviderName>
  <DefaultLocale>en-US</DefaultLocale>
  <DisplayName DefaultValue="${esc(addin.name)}"/>
  <Description DefaultValue="${esc(addin.description)}"/>
  <IconUrl DefaultValue="${appIcon(32)}"/>
  <HighResolutionIconUrl DefaultValue="${appIcon(64)}"/>
  <SupportUrl DefaultValue="https://github.com/bwbelding/retro-tab"/>
  <AppDomains>
    <AppDomain>${esc(origin)}</AppDomain>
  </AppDomains>
  <Hosts>
    <Host Name="Presentation"/>
  </Hosts>
  <DefaultSettings>
    <SourceLocation DefaultValue="${esc(viewUrl(addin.defaultView))}"/>
  </DefaultSettings>
  <Permissions>ReadWriteDocument</Permissions>
  <VersionOverrides xmlns="http://schemas.microsoft.com/office/taskpaneappversionoverrides" xsi:type="VersionOverridesV1_0">
    <Hosts>
      <Host xsi:type="Presentation">
        <DesktopFormFactor>
          <FunctionFile resid="${commandsUrl}"/>
          <ExtensionPoint xsi:type="PrimaryCommandSurface">
            <CustomTab id="${id("Tab")}">
${groups}
              <Label resid="${tabLabel}"/>
            </CustomTab>
          </ExtensionPoint>
        </DesktopFormFactor>
      </Host>
    </Hosts>
    <Resources>
      <bt:Images>
${images}
      </bt:Images>
      <bt:Urls>
${[...urls].map(([href, rid]) => `<bt:Url id="${rid}" DefaultValue="${esc(href)}"/>`).join("\n")}
      </bt:Urls>
      <bt:ShortStrings>
${shortStrings.map((t, i) => `<bt:String id="S${i + 1}" DefaultValue="${esc(t)}"/>`).join("\n")}
      </bt:ShortStrings>
      <bt:LongStrings>
${longStrings.map((t, i) => `<bt:String id="L${i + 1}" DefaultValue="${esc(t)}"/>`).join("\n")}
      </bt:LongStrings>
    </Resources>
  </VersionOverrides>
</OfficeApp>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { version } = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
  const baseUrl = process.env.RETRO_BASE_URL || DEFAULT_BASE_URL;
  const out = new URL("../dist/", import.meta.url);
  mkdirSync(out, { recursive: true });
  for (const addin of ADDINS) {
    const file = new URL(`manifest-${addin.key}.xml`, out);
    writeFileSync(file, buildManifest(addin, { baseUrl, version }));
    console.log(`wrote ${fileURLToPath(file)}`);
  }
  writeFileSync(new URL("version.json", out), JSON.stringify({ version, builtAt: new Date().toISOString() }) + "\n");
}
